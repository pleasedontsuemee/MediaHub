// MARK: - Video Item
public struct YTVideo: Identifiable, Hashable, Codable {
    public let id: String
    public let title: String
    public let channelId: String
    public let channelTitle: String
    public let channelAvatarURL: URL?
    public let channelSubscribers: String
    public let isChannelVerified: Bool
    public let thumbnailURL: URL?
    public let durationText: String
    public let durationSeconds: TimeInterval
    public let viewCountText: String
    public let publishedTimeText: String
    public let descriptionText: String
    public let hashtags: [String]
    public let likeCountText: String
    public let commentCountText: String
    public let isLive: Bool
    public let isUpcoming: Bool
    public let isShort: Bool
