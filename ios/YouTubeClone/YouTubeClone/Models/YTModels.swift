// MARK: - Resolved Playback Bundle (Returned by Embedded Engine)
public struct YTResolvedVideoPlayback {
    public let video: YTVideo
    public let hlsManifestURL: URL?
    public let muxedFormats: [YTVideoStreamFormat]
    public let adaptiveVideoFormats: [YTVideoStreamFormat]
    public let adaptiveAudioFormats: [YTVideoStreamFormat]
    public let captionTracks: [YTCaptionTrack]
    public let relatedVideos: [YTVideo]
    public let comments: [YTComment]

    public var availableQualityLabels: [String] {
        var labels: [String] = ["Auto (recommended)"]
        // Sort formats by height/width descending so 2160p (4K), 1440p, 1080p, 720p, 480p, 360p, 240p, 144p appear in order
        let sortedFormats = (adaptiveVideoFormats + muxedFormats)
            .filter { !$0.isAudioOnly }
            .sorted { ($0.width ?? 0) * ($0.height ?? 0) > ($1.width ?? 0) * ($1.height ?? 0) }

        for f in sortedFormats {
            let label = f.displayResolutionTitle
            if !label.isEmpty && !labels.contains(label) {
                labels.append(label)
            }
        }
        if labels.count == 1 {
            labels.append(contentsOf: ["2160p (4K)", "1440p (QHD)", "1080p", "720p", "480p", "360p", "240p", "144p"])
        }
        return labels
    }

    public static func targetHeight(for preferredQuality: String) -> Int? {
        guard preferredQuality != "Auto (recommended)", !preferredQuality.isEmpty else { return nil }
        if preferredQuality.contains("4320") || preferredQuality.contains("8K") { return 4320 }
        if preferredQuality.contains("2160") || preferredQuality.contains("4K") { return 2160 }
        if preferredQuality.contains("1440") || preferredQuality.contains("QHD") { return 1440 }
        let digits = preferredQuality
            .components(separatedBy: CharacterSet.decimalDigits.inverted)
            .first(where: { !$0.isEmpty })
        if let d = digits, let val = Int(d), val >= 144 {
            return val
        }
        return nil
    }

    public func matchingVideoFormat(for preferredQuality: String) -> YTVideoStreamFormat? {
        let allVideo = (adaptiveVideoFormats + muxedFormats).filter { !$0.isAudioOnly }
        if let exact = allVideo.first(where: { $0.displayResolutionTitle == preferredQuality || $0.qualityLabel == preferredQuality }) {
            return exact
        }
        if let targetH = Self.targetHeight(for: preferredQuality) {
            let avcMatches = allVideo.filter {
                $0.mimeType.contains("avc1") && ($0.height == targetH || min($0.width ?? 0, $0.height ?? 0) == targetH)
            }
            if let avc = avcMatches.first { return avc }
            let anyMatches = allVideo.filter {
                $0.height == targetH || min($0.width ?? 0, $0.height ?? 0) == targetH
            }
            if let any = anyMatches.first { return any }
        }
        // Prefix match (e.g. "2160p" or "1080p" or "144p")
        let prefix = preferredQuality.components(separatedBy: " ").first ?? preferredQuality
        return allVideo.first(where: { $0.qualityLabel.contains(prefix) || $0.displayResolutionTitle.contains(prefix) })
    }

    public var bestAudioFormat: YTVideoStreamFormat? {
        let aac140 = adaptiveAudioFormats.filter { $0.itag == 140 }
        let pool = aac140.isEmpty ? adaptiveAudioFormats : aac140
        // 1. Creator's true original audio track (e.g. "English (US) original", "Français original", or id "*.4")
        if let original = pool.first(where: {
            ($0.audioTrackName?.localizedCaseInsensitiveContains("original") == true)
            || ($0.audioTrackId?.hasSuffix(".4") == true)
        }) {
            return original
        }
        // 2. YouTube default track
        if let def = pool.first(where: { $0.isAudioDefault }) {
            return def
        }
        // 3. Fallback to first AAC 140 / first audio format
        return pool.first
    }

    public func bestPlayableURL(preferredQuality: String? = nil) -> URL? {
        if let hls = hlsManifestURL, (preferredQuality == nil || preferredQuality == "Auto (recommended)") {
            return hls
        }
        if let pref = preferredQuality, pref != "Auto (recommended)" {
            if let match = matchingVideoFormat(for: pref) {
                return match.url
            }
        }
        // For Auto, prefer 1080p or 720p adaptive or muxed
        if let hd = adaptiveVideoFormats.first(where: { ($0.height ?? 0) >= 720 && ($0.height ?? 0) <= 1080 }) {
            return hd.url
        }
        if let muxed = muxedFormats.first {
            return muxed.url
        }
        return adaptiveVideoFormats.first?.url
    }
}

